import { ArrowLeft, Download, FileImage, FileJson, FileText, Pencil } from 'lucide-react'
import { Link, useNavigate, useParams } from 'react-router-dom'
import { Shell } from '../components/Shell'
import { exportJson, exportMarkdown, exportPng, exportSvg } from '../lib/schematic-export'
import { createDraftId, saveDraft } from '../lib/schematic-store'
import { renderStaticSvg } from '../lib/schematic-svg'
import { getSchematic } from '../lib/schematics'
import { formatDate } from '../lib/posts'
import { useSeo } from '../lib/seo'
import NotFound from './NotFound'

export default function SchematicDetail() {
  const { slug = '' } = useParams()
  const navigate = useNavigate()
  const schematic = getSchematic(slug)
  useSeo({
    title: schematic?.title ?? 'Schematic',
    description: schematic?.description ?? 'A block diagram.',
    path: `/schematics/${slug}`,
    type: 'article',
  })

  if (!schematic) return <NotFound />

  const openInEditor = () => {
    const id = createDraftId()
    saveDraft(id, { ...schematic, title: `${schematic.title} (copy)` })
    navigate(`/schematics/draft/${id}`)
  }

  return (
    <Shell>
      <nav aria-label="Breadcrumb" className="mb-8">
        <Link to="/schematics" className="inline-flex items-center gap-1.5 text-sm text-muted transition-colors duration-200 hover:text-text">
          <ArrowLeft size={14} /> Schematics
        </Link>
      </nav>

      <header className="mb-8 max-w-[700px]">
        <div className="mono-meta flex flex-wrap items-center gap-x-3 gap-y-1">
          <time dateTime={schematic.date}>{formatDate(schematic.date, 'short')}</time>
          {schematic.nodes.length > 0 && (
            <span>
              {schematic.nodes.length} node{schematic.nodes.length === 1 ? '' : 's'} · {schematic.edges.length} connection
              {schematic.edges.length === 1 ? '' : 's'}
            </span>
          )}
        </div>
        <h1 className="mt-3 font-serif text-[32px] font-medium leading-[1.15] tracking-[-0.01em] text-text sm:text-[38px]">{schematic.title}</h1>
        {schematic.description && <p className="mt-3 text-[16px] leading-relaxed text-text-2">{schematic.description}</p>}
        {schematic.tags.length > 0 && (
          <ul className="mt-4 flex flex-wrap gap-1.5">
            {schematic.tags.map((t) => (
              <li key={t} className="chip font-mono !min-h-6 !text-[12px] !px-2">
                {t}
              </li>
            ))}
          </ul>
        )}
      </header>

      <div
        className="mb-6 overflow-auto rounded-card border border-border [&>svg]:block [&>svg]:max-w-none"
        // Generated by our own renderStaticSvg from this page's own data, not user HTML.
        dangerouslySetInnerHTML={{ __html: renderStaticSvg(schematic) }}
      />

      <div className="flex flex-wrap gap-2">
        <button type="button" className="btn-ghost" onClick={openInEditor}>
          <Pencil size={15} /> Open in editor
        </button>
        <button type="button" className="btn-ghost" onClick={() => exportJson(schematic)}>
          <FileJson size={15} /> .json
        </button>
        <button type="button" className="btn-ghost" onClick={() => exportSvg(schematic)}>
          <Download size={15} /> .svg
        </button>
        <button type="button" className="btn-ghost" onClick={() => void exportPng(schematic)}>
          <FileImage size={15} /> .png
        </button>
        <button type="button" className="btn-ghost" onClick={() => exportMarkdown(schematic)}>
          <FileText size={15} /> .md
        </button>
      </div>
    </Shell>
  )
}
